-- =============================================================
-- comments.reply_count：返信の総数（テーブル定義書 5.2）
--
-- 【確定】コメント一覧を「返信が多い順」に並べるため（要件定義書4.3）。
-- アプリに保存される返信は、1スレッドにつき YouTube が同梱する数件だけ（要件定義書7.3）なので、
-- 保存してある返信を数えても正しい順にならない。
-- そこで、YouTube が返す返信の総数（commentThreads.list の totalReplyCount）をそのまま保存する。
-- この値は、もともと受け取っている応答に入っているので、YouTube への問い合わせは増えない。
-- 入るのは親コメントだけ。返信の行は NULL。
-- =============================================================

alter table public.comments
  add column reply_count integer;
