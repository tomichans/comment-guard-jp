/** YouTube API の1リクエストで取得できるスレッド数の上限（API の仕様。要件定義書7.1） */
export const THREADS_PER_PAGE = 100;

/** ゲストのコメント取得上限（スレッド数） */
export const GUEST_MAX_THREADS = 100;

/** ログインユーザーのコメント取得上限（スレッド数） */
export const USER_MAX_THREADS = 1000;

/**
 * ゲストが同じIPアドレスから、直近24時間に動画を登録しようとできる回数。
 * Cookie を消せば新しいゲストになれるため、IP単位でも上限を設ける（要件定義書3.1）。
 * 数えるのは「YouTube に動画情報を問い合わせた回数」（存在しない動画も含む）。
 * 値は5本で確定（要件定義書3.1）。
 */
export const GUEST_DAILY_VIDEO_LIMIT = 5;

/**
 * ログインユーザー1人が、直近24時間に動画を登録しようとできる回数【確定】（要件定義書3.2、14.2）。
 * 数え方はゲストの IP単位の上限と同じ（YouTube に動画情報を問い合わせた回数。存在しない動画も含む）。
 * 動画を削除しても回数は減らない（api_usage_logs は動画を消しても残るため）。
 */
export const USER_DAILY_VIDEO_LIMIT = 10;

/**
 * アプリ全体（ゲストとログインユーザーの合計）で、直近24時間に動画を登録しようとできる回数【確定】（要件定義書14.2）。
 * メール確認なしで何個でもアカウントを作れるので、1人あたりの上限だけでは、作り直せば使い続けられてしまう。
 * AI の費用が膨らまないよう、全体にも上限をかける。
 */
export const SERVICE_DAILY_VIDEO_LIMIT = 50;
